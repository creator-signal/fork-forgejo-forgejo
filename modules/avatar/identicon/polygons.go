// b3: diamond
//
//	---------
//	|   #   |
//	|  ###  |
//	| ##### |
//	|#######|
//	| ##### |
//	|  ###  |
//	|   #   |
//	---------

func b3p1(size int) []int {
	m := size / 2
	return []int{
		m, 0,
		size, m,
		m, size,
		0, m,
	}
}

